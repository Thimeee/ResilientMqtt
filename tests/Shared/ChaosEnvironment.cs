namespace ResilientMqtt.TestKit
{
    /// <summary>One broker of the docker test environment (tests/chaos/docker-compose.yml).</summary>
    internal sealed record BrokerTarget(string Name, int DirectPort, int ProxyPort, string ProxyName, string Upstream, bool Auth, string Container);

    /// <summary>Where the docker test environment lives and which brokers are up (env vars set by tests/run-all.ps1).</summary>
    internal static class ChaosEnvironment
    {
        public const string Host = "127.0.0.1";
        public const string User = "test";
        public const string Password = "test";

        public static readonly BrokerTarget Mosquitto = new("mosquitto", 18831, 18901, "mosquitto", "mosquitto:1883", Auth: true, "rmqtt-mosquitto");
        public static readonly BrokerTarget Emqx = new("emqx", 18841, 18902, "emqx", "emqx:1883", Auth: false, "rmqtt-emqx");
        public static readonly BrokerTarget HiveMq = new("hivemq", 18851, 18903, "hivemq", "hivemq:1883", Auth: false, "rmqtt-hivemq");
        public static readonly BrokerTarget[] All = { Mosquitto, Emqx, HiveMq };

        public const int MosquittoTlsPort = 18832;
        public const int MosquittoMutualTlsPort = 18833;
        public const string ToxiproxyApi = "http://127.0.0.1:18474";

        /// <summary>Chaos tests run only when RMQTT_CHAOS=1 (set by run-all.ps1) — a plain `dotnet test` skips them.</summary>
        public static bool Enabled => Environment.GetEnvironmentVariable("RMQTT_CHAOS") == "1";

        /// <summary>Brokers that are up, e.g. "mosquitto,emqx,hivemq" (RMQTT_BROKERS; default mosquitto).</summary>
        public static bool BrokerEnabled(string name)
            => (Environment.GetEnvironmentVariable("RMQTT_BROKERS") ?? "mosquitto")
               .Split(',', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries)
               .Contains(name, StringComparer.OrdinalIgnoreCase);

        public static BrokerTarget Broker(string name) => All.Single(b => b.Name == name);

        /// <summary>Folder with ca.pem / server.pem / client.pfx generated by `LoadTest certs` (RMQTT_CERTS).</summary>
        public static string CertDir => Environment.GetEnvironmentVariable("RMQTT_CERTS")
            ?? Path.GetFullPath(Path.Combine(AppContext.BaseDirectory, "..", "..", "..", "..", "chaos", "certs"));

        public const string ClientPfxPassword = "rmqtt-test";

        public static async Task<bool> PortOpenAsync(int port)
        {
            try
            {
                using var tcp = new TcpClient();
                await tcp.ConnectAsync(Host, port).WaitAsync(TimeSpan.FromSeconds(2));
                return true;
            }
            catch { return false; }
        }

        /// <summary>Library options pointing at a test broker (agent-like defaults; tweak per test).</summary>
        public static ResilientMqttOptions Options(BrokerTarget broker, bool viaProxy, Action<ResilientMqttOptions>? configure = null)
        {
            var o = new ResilientMqttOptions
            {
                Host = Host,
                Port = viaProxy ? broker.ProxyPort : broker.DirectPort,
                ClientId = "chaos-" + Guid.NewGuid().ToString("N")[..10],
                Username = User,
                Password = Password,
                KeepAliveSeconds = 30,
                CleanSession = true,
            };
            o.LastWill.Enabled = false;
            o.OfflineBuffer.Enabled = false;
            o.HealthCheck.Enabled = false;
            o.Reconnect.ConnectTimeoutSeconds = 5;
            o.Reconnect.StillDownAfterSeconds = 0;
            configure?.Invoke(o);
            return o;
        }

        /// <summary>Builds a client through the internal constructor so tests can pass a fast health check / retry.</summary>
        public static IResilientMqttClient CreateClient(
            ResilientMqttOptions options,
            ILogger<ResilientMqttClient>? logger = null,
            TimeSpan? healthInterval = null,
            TimeSpan? retryDelay = null,
            bool realBackoff = false)
        {
            IHealthCheck health = healthInterval is { } every
                ? new IdleAwareHealthCheck(every, every, TimeSpan.FromSeconds(Math.Max(1, options.HealthCheck.PingTimeoutSeconds)), NullLogger.Instance)
                : new NullHealthCheck();
            IRetryStrategy retry = realBackoff
                ? new ExponentialBackoffStrategy(TimeSpan.FromSeconds(options.Reconnect.BaseDelaySeconds),
                    TimeSpan.FromSeconds(options.Reconnect.MaxDelaySeconds), options.Reconnect.UseJitter)
                : new ConstantRetry(retryDelay ?? TimeSpan.FromMilliseconds(250));
            IOfflineBuffer buffer = options.OfflineBuffer.Enabled
                ? new InMemoryOfflineBuffer(options.OfflineBuffer.MaxSize, NullLogger.Instance)
                : new NullOfflineBuffer();
            return new ResilientMqttClient(new MqttClientFactory().CreateMqttClient(), Microsoft.Extensions.Options.Options.Create(options),
                retry, health, buffer, new NullCircuitBreaker(), logger ?? NullLogger<ResilientMqttClient>.Instance);
        }

        public static async Task<bool> Eventually(Func<bool> condition, TimeSpan timeout)
        {
            var deadline = DateTime.UtcNow + timeout;
            while (DateTime.UtcNow < deadline)
            {
                if (condition()) return true;
                await Task.Delay(50);
            }
            return condition();
        }

        /// <summary>docker CLI (restart / stop / start a broker container).</summary>
        public static async Task DockerAsync(string args)
        {
            using var p = System.Diagnostics.Process.Start(new System.Diagnostics.ProcessStartInfo("docker", args)
            {
                RedirectStandardOutput = true,
                RedirectStandardError = true,
                UseShellExecute = false,
            })!;
            await p.WaitForExitAsync();
            if (p.ExitCode != 0)
                throw new InvalidOperationException($"docker {args} failed: {await p.StandardError.ReadToEndAsync()}");
        }
    }

    internal sealed class ConstantRetry(TimeSpan delay) : IRetryStrategy
    {
        public TimeSpan GetNextDelay(int attempt) => delay;
    }

    /// <summary>Minimal client for the Toxiproxy HTTP API (https://github.com/Shopify/toxiproxy).</summary>
    internal sealed class Toxiproxy : IDisposable
    {
        private readonly HttpClient _http;

        public Toxiproxy(string apiBase = ChaosEnvironment.ToxiproxyApi)
            => _http = new HttpClient { BaseAddress = new Uri(apiBase), Timeout = TimeSpan.FromSeconds(10) };

        /// <summary>(Re)creates one proxy per broker. Idempotent.</summary>
        public async Task EnsureProxiesAsync(IEnumerable<BrokerTarget> brokers)
        {
            foreach (var b in brokers)
            {
                await _http.DeleteAsync($"/proxies/{b.ProxyName}");   // 404 when absent — fine
                var resp = await _http.PostAsJsonAsync("/proxies", new
                {
                    name = b.ProxyName,
                    listen = $"0.0.0.0:{b.ProxyPort}",
                    upstream = b.Upstream,
                    enabled = true,
                });
                resp.EnsureSuccessStatusCode();
            }
        }

        /// <summary>Removes every toxic and re-enables every proxy.</summary>
        public async Task ResetAsync() => (await _http.PostAsync("/reset", null)).EnsureSuccessStatusCode();

        public async Task SetEnabledAsync(BrokerTarget b, bool enabled)
            => (await _http.PostAsJsonAsync($"/proxies/{b.ProxyName}", new { enabled })).EnsureSuccessStatusCode();

        /// <param name="stream">"downstream" (broker → client) or "upstream" (client → broker).</param>
        public async Task AddToxicAsync(BrokerTarget b, string name, string type, string stream, object attributes)
        {
            var resp = await _http.PostAsJsonAsync($"/proxies/{b.ProxyName}/toxics", new
            {
                name,
                type,
                stream,
                toxicity = 1.0,
                attributes,
            });
            if (!resp.IsSuccessStatusCode)
                throw new InvalidOperationException($"toxiproxy: adding {type} failed: {await resp.Content.ReadAsStringAsync()}");
        }

        public async Task RemoveToxicAsync(BrokerTarget b, string name) => await _http.DeleteAsync($"/proxies/{b.ProxyName}/toxics/{name}");

        public async Task<bool> IsUpAsync()
        {
            try { return (await _http.GetAsync("/version")).IsSuccessStatusCode; }
            catch { return false; }
        }

        public void Dispose() => _http.Dispose();
    }
}
